// Writes the migration that gives Hindi Word EFFICIENCY TEST 7 its new paper (24 Nov 2026) as a NEW version: the same
// practice document, 15 new questions (tests/fixtures/hindi-word-tests-7-8.json, built by build-hindi-word-tests-7-8.mts),
// their hand-written checks and Hindi solutions, and the Model Answer solved in the real editor
// (tests/fixtures/hindi-word-test7-v2-model.json). Checked by tests/hindi-word-test7-v2-rules-runtime.test.mjs.
//   node scripts/build-hindi-word-test7-v2-migration.mjs
import { readFileSync, writeFileSync } from "node:fs";

const paper = JSON.parse(readFileSync("tests/fixtures/hindi-word-tests-7-8.json", "utf8")).tests[0];
const model = JSON.parse(readFileSync("tests/fixtures/hindi-word-test7-v2-model.json", "utf8"));
if (paper.title !== "EFFICIENCY TEST 7" || paper.questions.length !== 15) throw new Error("unexpected Test 7 paper");
const dollar = (text) => { let tag = "$q$"; for (let i = 0; text.includes(tag); i++) tag = `$q${i}$`; return `${tag}${text}${tag}`; };
const marks = paper.questions.map((_, index, all) => (index === all.length - 1 ? Math.round((25 - 1.66 * (all.length - 1)) * 100) / 100 : 1.66));
const questions = paper.questions.map((question, index) => ({ number: index + 1, instruction: question.instruction, marks: marks[index], criteria: question.criteria, solution: question.solution }));
// The ribbon tools the new questions need, switched on in the new version's editor settings (tab, group, option).
// TABLE TOOLS (Design / Layout) show whenever the cursor is in a table; Hyphenation shows with Line Numbers.
const tools = [
  ["Home", "font", "increaseFontSize"], ["Home", "font", "fontDialog"],
  ["Home", "paragraph", "bullets"], ["Home", "paragraph", "paragraphDialog"],
  ["Insert", "tables", "insertTable"],
  ["Design", "pageBackground", "pageBorders"],
  ["Page Layout", "pageSetup", "columns"], ["Page Layout", "pageSetup", "lineNumbers"], ["Page Layout", "pageSetup", "margins"], ["Page Layout", "pageSetup", "sectionBreak"],
];

const sql = `-- Hindi Word EFFICIENCY TEST 7: a new paper (24 Nov 2026). The old one asked the same kinds of questions as Tests 5, 6
-- and 8 (font size/colour, Change Case, superscript, Justify + line spacing, numbering, sort, Replace All, Page Break,
-- Insert Table, ©, header + page number, page border, Orientation + Margins). Every new question asks for a Word 2013
-- tool that no other Word Efficiency paper (Hindi or English) uses:
--   HOME Font: Grow Font (A↑) twice, Small caps, Hidden.   HOME Paragraph: Spacing Before 24 pt, Checkmark bullets.
--   TABLE TOOLS: Table Style "Grid Table 4 - Accent 1", Alignment Center, Delete Columns, Repeat Header Rows.
--   DESIGN: Page Border > Options > Measure from Text.
--   PAGE LAYOUT: Two Columns, Line Numbers, Hyphenation, Gutter 1", Section Break (Next Page).
-- Same practice document. The test gets a NEW version (students' earlier attempts stay on their own version with their
-- marks), with hand-written checks, Hindi solutions and the Model Answer solved in the real editor; results are
-- published automatically. The tools the questions need are switched on in the new version's editor settings.
-- Generated by scripts/build-hindi-word-test7-v2-migration.mjs. Safe to run twice (skipped once Test 7 has this paper).
begin;

create temporary table new_paper (questions jsonb, model jsonb) on commit drop;
insert into new_paper values (${dollar(JSON.stringify(questions))}::jsonb, ${dollar(JSON.stringify(model))}::jsonb);

do $$
declare p record; old record; new_id uuid; q jsonb; question_id uuid; caps jsonb; tool text[];
begin
  select * into p from new_paper;
  select v.* into old from public.word_efficiency_tests t join public.word_efficiency_versions v on v.id = t.current_version_id
   where t.language = 'Hindi' and t.title = 'EFFICIENCY TEST 7';
  if old.id is null then raise exception 'Hindi Word EFFICIENCY TEST 7 not found'; end if;
  if exists (select 1 from public.word_efficiency_questions where version_id = old.id and question_number = 1 and instruction = p.questions->0->>'instruction') then
    raise notice 'Hindi Word EFFICIENCY TEST 7 already has the new paper'; return;
  end if;
  caps := coalesce(old.editor_capabilities, '{}'::jsonb);
  foreach tool slice 1 in array array[${tools.map((t) => `array[${t.map((part) => `'${part}'`).join(",")}]`).join(", ")}] loop
    caps := jsonb_set(caps, array['tabs'], coalesce(caps->'tabs', '{}'::jsonb));
    caps := jsonb_set(caps, array['tabs', tool[1]], coalesce(caps #> array['tabs', tool[1]], '{}'::jsonb) || '{"enabled": true}');
    caps := jsonb_set(caps, array['tabs', tool[1], 'groups'], coalesce(caps #> array['tabs', tool[1], 'groups'], '{}'::jsonb));
    caps := jsonb_set(caps, array['tabs', tool[1], 'groups', tool[2]], coalesce(caps #> array['tabs', tool[1], 'groups', tool[2]], '{}'::jsonb) || '{"enabled": true}');
    caps := jsonb_set(caps, array['tabs', tool[1], 'groups', tool[2], 'options'], coalesce(caps #> array['tabs', tool[1], 'groups', tool[2], 'options'], '{}'::jsonb));
    caps := jsonb_set(caps, array['tabs', tool[1], 'groups', tool[2], 'options', tool[3]], 'true');
  end loop;
  insert into public.word_efficiency_versions (test_id, version_number, title, language, description, instructions_markdown, delivery_onscreen, delivery_pdf, delivery_realfile,
      student_question_toggle, question_count, maximum_marks, duration_options, passing_marks, created_by, working_matter_snapshot, editor_capabilities, model_answer_snapshot)
  values (old.test_id, (select max(version_number) + 1 from public.word_efficiency_versions where test_id = old.test_id), old.title, old.language, old.description, old.instructions_markdown,
      true, false, false, old.student_question_toggle, jsonb_array_length(p.questions), 25, old.duration_options, old.passing_marks, old.created_by, old.working_matter_snapshot, caps, p.model)
  returning id into new_id;
  for q in select value from jsonb_array_elements(p.questions) loop
    insert into public.word_efficiency_questions (version_id, question_number, instruction, marks, section, display_order, is_visible, solution)
    values (new_id, (q->>'number')::integer, q->>'instruction', (q->>'marks')::numeric, null, (q->>'number')::integer, true, q->>'solution')
    returning id into question_id;
    insert into public.word_efficiency_grading_rules (version_id, question_id, exact_target, expected_operation, expected_value, allocated_marks, partial_marks, additional_criteria, part_label)
    values (new_id, question_id, 'rule', 'model-answer-match-v2', 'null'::jsonb, (q->>'marks')::numeric, null, q->'criteria', null);
  end loop;
  update public.word_efficiency_tests set current_version_id = new_id, current_version_number = (select version_number from public.word_efficiency_versions where id = new_id),
      auto_publish_results = true, updated_at = now()
   where id = old.test_id;
end $$;

-- Check: the Model Answer must earn every question's marks (25), the untouched paper none (0), and every tool the
-- questions need must be switched on (tools_off empty).
select t.title, t.current_version_number, v.question_count, sum(q.marks) total,
       sum((public.word_efficiency_score_question(v.model_answer_snapshot, v.id, q.id, q.marks, v.model_answer_snapshot)).awarded) model_answer_gets,
       sum((public.word_efficiency_score_question(public.word_efficiency_initial_editor_document(v.working_matter_snapshot), v.id, q.id, q.marks, v.model_answer_snapshot)).awarded) untouched_paper_gets,
       (select coalesce(string_agg(tool, ', '), '') from unnest(array[${tools.map((t) => `'${t.join("/")}'`).join(", ")}]) tool
         where coalesce(v.editor_capabilities #>> array['tabs', split_part(tool, '/', 1), 'groups', split_part(tool, '/', 2), 'options', split_part(tool, '/', 3)], 'false') <> 'true') tools_off
  from public.word_efficiency_tests t join public.word_efficiency_versions v on v.id = t.current_version_id join public.word_efficiency_questions q on q.version_id = v.id
 where t.language = 'Hindi' and t.title = 'EFFICIENCY TEST 7'
 group by t.title, t.current_version_number, v.question_count, v.editor_capabilities;

commit;
`;
writeFileSync("supabase/migrations/202611241200_hindi_word_test7_new_questions.sql", sql);
console.log(sql.length);
