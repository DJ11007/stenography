// Writes the migration that adds the new Hindi Word EFFICIENCY TEST 7 and TEST 8 papers (from
// tests/fixtures/hindi-word-tests-7-8.json, built by build-hindi-word-tests-7-8.mts) as NEW versions of the two tests.
//   node scripts/build-hindi-word-tests-7-8-migration.mjs
import { readFileSync, writeFileSync } from "node:fs";

const spec = JSON.parse(readFileSync("tests/fixtures/hindi-word-tests-7-8.json", "utf8"));
const dollar = (text) => { let tag = "$q$"; for (let i = 0; text.includes(tag); i++) tag = `$q${i}$`; return `${tag}${text}${tag}`; };
const marksFor = (count) => { const base = Math.floor((25 / count) * 100) / 100; return Array.from({ length: count }, (_, i) => (i === count - 1 ? Math.round((25 - base * (count - 1)) * 100) / 100 : base)); };

let sql = `-- Hindi Word EFFICIENCY TEST 7 and TEST 8: new papers (7 Nov 2026). The old ones asked Test 6's questions on documents
-- they did not fit. Each test gets a NEW version (students' earlier attempts stay on their own version with their marks):
-- a practice document (Kruti Dev Hindi paragraph, three English paragraphs, a list, two short lines, a table), 15 / 16
-- questions over HOME Font / Paragraph / Editing, INSERT Pages / Table / Header & Footer / Symbols, DESIGN Page Background
-- and PAGE LAYOUT Page Setup, hand-written marking checks (kept when the Model Answer page is saved) and Hindi solutions.
-- Results are not published automatically yet: the admin solves the Model Answer first.
-- Generated by scripts/build-hindi-word-tests-7-8-migration.mjs. Safe to run twice (a test already on this paper is skipped).
begin;

create temporary table new_paper (title text, matter jsonb, questions jsonb) on commit drop;
insert into new_paper values\n`;
sql += spec.tests.map((test) => {
  const marks = marksFor(test.questions.length);
  const questions = test.questions.map((question, index) => ({ number: index + 1, instruction: question.instruction, marks: marks[index], criteria: question.criteria, solution: question.solution }));
  return ` (${dollar(test.title)}, ${dollar(JSON.stringify(test.matter))}::jsonb, ${dollar(JSON.stringify(questions))}::jsonb)`;
}).join(",\n") + ";\n";

sql += `
do $$
declare p record; old record; new_id uuid; q jsonb; question_id uuid;
begin
  for p in select * from new_paper loop
    select v.* into old from public.word_efficiency_tests t join public.word_efficiency_versions v on v.id = t.current_version_id
     where t.language = 'Hindi' and t.title = p.title;
    if old.id is null then raise exception 'Hindi Word % not found', p.title; end if;
    continue when old.working_matter_snapshot = p.matter;
    insert into public.word_efficiency_versions (test_id, version_number, title, language, description, instructions_markdown, delivery_onscreen, delivery_pdf, delivery_realfile,
        student_question_toggle, question_count, maximum_marks, duration_options, passing_marks, created_by, working_matter_snapshot, editor_capabilities, model_answer_snapshot)
    values (old.test_id, (select max(version_number) + 1 from public.word_efficiency_versions where test_id = old.test_id), old.title, old.language, old.description, old.instructions_markdown,
        true, false, false, old.student_question_toggle, jsonb_array_length(p.questions), 25, old.duration_options, old.passing_marks, old.created_by, p.matter, old.editor_capabilities, null)
    returning id into new_id;
    for q in select value from jsonb_array_elements(p.questions) loop
      insert into public.word_efficiency_questions (version_id, question_number, instruction, marks, section, display_order, is_visible, solution)
      values (new_id, (q->>'number')::integer, q->>'instruction', (q->>'marks')::numeric, null, (q->>'number')::integer, true, q->>'solution')
      returning id into question_id;
      insert into public.word_efficiency_grading_rules (version_id, question_id, exact_target, expected_operation, expected_value, allocated_marks, partial_marks, additional_criteria, part_label)
      values (new_id, question_id, 'rule', 'model-answer-match-v2', 'null'::jsonb, (q->>'marks')::numeric, null, q->'criteria', null);
    end loop;
    update public.word_efficiency_tests set current_version_id = new_id, current_version_number = (select version_number from public.word_efficiency_versions where id = new_id),
        auto_publish_results = false, updated_at = now()
     where id = old.test_id;
  end loop;
end $$;

select t.title, t.current_version_number, v.question_count, v.maximum_marks,
       (select count(*) from public.word_efficiency_grading_rules r where r.version_id = v.id) checks
  from public.word_efficiency_tests t join public.word_efficiency_versions v on v.id = t.current_version_id
 where t.language = 'Hindi' and t.title in ('EFFICIENCY TEST 7', 'EFFICIENCY TEST 8') order by t.title;

commit;
`;
writeFileSync("supabase/migrations/202611072400_hindi_word_tests_7_8_new_papers.sql", sql);
console.log(sql.length);
