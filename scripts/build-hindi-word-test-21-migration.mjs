// Writes the migration that adds Hindi Word EFFICIENCY TEST 21 (28 Nov 2026): the owner's previous-year exam paper
// (tests/fixtures/hindi-word-test-21.json, built by build-hindi-word-test-21.mts) with its 15 questions, hand-written
// checks and Hindi solutions, and the Model Answer solved in the real editor (tests/fixtures/hindi-word-test-21-model.json).
// The migration checks itself before publishing: the Model Answer must earn all 25 marks and the untouched paper 0,
// otherwise it stops and nothing is added. Checked again by tests/hindi-word-test-21-rules-runtime.test.mjs.
//   node scripts/build-hindi-word-test-21-migration.mjs
import { readFileSync, writeFileSync } from "node:fs";

const spec = JSON.parse(readFileSync("tests/fixtures/hindi-word-test-21.json", "utf8"));
const model = JSON.parse(readFileSync("tests/fixtures/hindi-word-test-21-model.json", "utf8"));
if (spec.title !== "EFFICIENCY TEST 21" || spec.questions.length !== 15) throw new Error("unexpected paper");
const dollar = (text) => { let tag = "$q$"; for (let i = 0; text.includes(tag); i++) tag = `$q${i}$`; return `${tag}${text}${tag}`; };
const marks = spec.questions.map((_, index, all) => (index === all.length - 1 ? Math.round((25 - 1.66 * (all.length - 1)) * 100) / 100 : 1.66));
const questions = spec.questions.map((question, i) => ({ number: i + 1, instruction: question.instruction, marks: marks[i], criteria: question.criteria, solution: question.solution }));

const sql = `-- Hindi Word EFFICIENCY TEST 21 (28 Nov 2026): a previous-year exam paper (RSMSSB) sent by the owner as an image,
-- kept question for question (Q.1 अ ब स ... Q.5 अ ब स -> questions 1 to 15): Landscape, right indent 1.1", line spacing
-- 1.5, remove paragraph shading, font colours, header page number starting at 3, subscript, font size 15, DO NOT COPY
-- watermark, remove double strikethrough, blue highlight, gutter 0.5" at the top, and the table's first column (remove
-- underline), third column (bold, red) and rows 1 and 3 (justify). Practice document: a Mangal Hindi passage about the
-- national flag with a table; the "remove" questions' formatting is part of it (migration 202611271000).
-- The editor settings are Hindi Test 20's (every tool of HOME, INSERT, DESIGN and PAGE LAYOUT). Results are published
-- automatically, as for Tests 11-20.
-- Self-check: the test is published only when the Model Answer earns 25 and the untouched paper 0; otherwise the
-- migration stops and nothing is added. Safe to run twice (skipped when Test 21 exists).
-- Generated by scripts/build-hindi-word-test-21-migration.mjs.
do $$
declare base record; test_id uuid; new_id uuid; q jsonb; question_id uuid; model_gets numeric; untouched_gets numeric;
  matter jsonb := ${dollar(JSON.stringify(spec.matter))}::jsonb;
  model jsonb := ${dollar(JSON.stringify(model))}::jsonb;
  qs jsonb := ${dollar(JSON.stringify(questions))}::jsonb;
begin
  if exists (select 1 from public.word_efficiency_tests where language = 'Hindi' and title = 'EFFICIENCY TEST 21') then return; end if;
  select t.created_by as test_created_by, v.* into base from public.word_efficiency_tests t join public.word_efficiency_versions v on v.id = t.current_version_id
   where t.language = 'Hindi' and t.title = 'EFFICIENCY TEST 20';
  if base.id is null then raise exception 'Hindi Word EFFICIENCY TEST 20 not found (its settings are copied)'; end if;

  insert into public.word_efficiency_tests (slug, title, status, is_live, language, sequence, created_by, auto_publish_results, question_paper_ready, results_delay_minutes, current_version_number)
  values ('hindi-efficiency-test-21', 'EFFICIENCY TEST 21', 'draft', false, 'Hindi', 21, base.test_created_by, true, true, 15, 1)
  returning id into test_id;

  insert into public.word_efficiency_versions (test_id, version_number, title, language, description, instructions_markdown, delivery_onscreen, delivery_pdf, delivery_realfile,
      student_question_toggle, question_count, maximum_marks, duration_options, passing_marks, created_by, working_matter_snapshot, editor_capabilities, model_answer_snapshot)
  values (test_id, 1, 'EFFICIENCY TEST 21', 'Hindi', 'Previous-year exam paper (RSMSSB): Page Layout, Home, Insert and Design tab tasks on a Hindi document with a table: National Flag',
      base.instructions_markdown, true, false, false, base.student_question_toggle, jsonb_array_length(qs), 25, base.duration_options, base.passing_marks, base.created_by,
      matter, base.editor_capabilities, model)
  returning id into new_id;

  for q in select value from jsonb_array_elements(qs) loop
    insert into public.word_efficiency_questions (version_id, question_number, instruction, marks, section, display_order, is_visible, solution)
    values (new_id, (q->>'number')::integer, q->>'instruction', (q->>'marks')::numeric, null, (q->>'number')::integer, true, q->>'solution')
    returning id into question_id;
    insert into public.word_efficiency_grading_rules (version_id, question_id, exact_target, expected_operation, expected_value, allocated_marks, partial_marks, additional_criteria, part_label)
    values (new_id, question_id, 'rule', 'model-answer-match-v2', 'null'::jsonb, (q->>'marks')::numeric, null, q->'criteria', null);
  end loop;
  update public.word_efficiency_tests set current_version_id = new_id where id = test_id;

  select sum((public.word_efficiency_score_question(model, new_id, wq.id, wq.marks, model)).awarded),
         sum((public.word_efficiency_score_question(public.word_efficiency_initial_editor_document(matter), new_id, wq.id, wq.marks, model)).awarded)
    into model_gets, untouched_gets
    from public.word_efficiency_questions wq where wq.version_id = new_id;
  if model_gets <> 25 or untouched_gets <> 0 then
    raise exception 'Hindi Word Test 21 check failed: Model Answer gets %, untouched paper gets % (want 25 and 0)', model_gets, untouched_gets;
  end if;
  update public.word_efficiency_tests set status = 'published', published_at = now(), updated_at = now() where id = test_id;
end $$;
`;
writeFileSync("supabase/migrations/202611281000_hindi_word_test_21_previous_year_paper.sql", sql);
console.log(sql.length);
