// Writes the migration that stores the solved Hindi Word Test 7 / Test 8 papers (tests/fixtures/hindi-word-test7-model.json,
// hindi-word-test8-model.json, solved in the editor) as the two tests' Model Answers, and turns automatic publishing on.
// Test 8's saved paper missed Q1 (size 15) and Q2 (Times New Roman 13) only because the font boxes did not take the
// typing in that run (both were done and checked in an earlier run); they are set here as the paper asks.
//   node scripts/build-hindi-word-tests-7-8-model-answers.mjs
import { readFileSync, writeFileSync } from "node:fs";

const test7 = JSON.parse(readFileSync("tests/fixtures/hindi-word-test7-model.json", "utf8"));
const test8 = JSON.parse(readFileSync("tests/fixtures/hindi-word-test8-model.json", "utf8"));
const body8 = test8.blocks.filter((block) => !["header", "footer"].includes(block.type));
for (const run of body8[0].runs) run.fontSize = 15;
for (const run of body8[1].runs) { run.fontFamily = "Times New Roman"; run.fontSize = 13; }

const dollar = (text) => { let tag = "$m$"; for (let i = 0; text.includes(tag); i++) tag = `$m${i}$`; return `${tag}${text}${tag}`; };
const sql = `-- Hindi Word EFFICIENCY TEST 7 and TEST 8: the solved papers become the Model Answers (the marking uses the hand-written
-- checks; the Model Answer is what the Model Answer page and the Auto-grading check show), and results are published
-- automatically from now on. Generated by scripts/build-hindi-word-tests-7-8-model-answers.mjs. Safe to run twice.
begin;

update public.word_efficiency_versions v set model_answer_snapshot = ${dollar(JSON.stringify(test7))}::jsonb
  from public.word_efficiency_tests t where t.current_version_id = v.id and t.language = 'Hindi' and t.title = 'EFFICIENCY TEST 7';
update public.word_efficiency_versions v set model_answer_snapshot = ${dollar(JSON.stringify(test8))}::jsonb
  from public.word_efficiency_tests t where t.current_version_id = v.id and t.language = 'Hindi' and t.title = 'EFFICIENCY TEST 8';
update public.word_efficiency_tests set auto_publish_results = true where language = 'Hindi' and title in ('EFFICIENCY TEST 7', 'EFFICIENCY TEST 8');

-- Check: the Model Answer must earn every question's marks, the untouched paper none.
select t.title, sum(q.marks) total,
       sum((public.word_efficiency_score_question(v.model_answer_snapshot, v.id, q.id, q.marks, v.model_answer_snapshot)).awarded) model_answer_gets,
       sum((public.word_efficiency_score_question(public.word_efficiency_initial_editor_document(v.working_matter_snapshot), v.id, q.id, q.marks, v.model_answer_snapshot)).awarded) untouched_paper_gets
  from public.word_efficiency_tests t join public.word_efficiency_versions v on v.id = t.current_version_id join public.word_efficiency_questions q on q.version_id = v.id
 where t.language = 'Hindi' and t.title in ('EFFICIENCY TEST 7', 'EFFICIENCY TEST 8') group by t.title order by t.title;

commit;
`;
writeFileSync("supabase/migrations/202611081100_hindi_word_tests_7_8_model_answers.sql", sql);
writeFileSync(process.argv[2] ?? "/dev/null", JSON.stringify(test8));
console.log(sql.length);
